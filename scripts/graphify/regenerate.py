def _norm(p: str) -> str:
    return str(Path(p)).replace("\\", "/").lower()


def find_graphify() -> str:
    """Return the path/argv prefix used to invoke the graphify CLI."""
    venv = os.environ.get("GRAPHIFY_VENV")
    if venv:
        exe = Path(venv) / ("Scripts/graphify.exe" if os.name == "nt" else "bin/graphify")
        if exe.exists():
            return str(exe)
        print(f"[graphify] GRAPHIFY_VENV set but {exe} not found", file=sys.stderr)
    cli = shutil.which("graphify")
    if cli:
        return cli
    probe = subprocess.run([sys.executable, "-m", "graphify", "--version"],
                           capture_output=True)
    if probe.returncode == 0:
        return [sys.executable, "-m", "graphify"]
    print(
        "error: graphify not found. Install it (pip install graphifyy) or set "
        "GRAPHIFY_VENV to the venv directory.",
        file=sys.stderr,
    )
    sys.exit(1)


def run_cli(graphify: str | list[str], *args: str) -> None:
    cmd = [*graphify, *args] if isinstance(graphify, list) else [graphify, *args]
    print(f"[graphify] {' '.join(str(a) for a in cmd)}")
    proc = subprocess.run(cmd)
    if proc.returncode != 0:
        print(f"error: command failed ({proc.returncode})", file=sys.stderr)
        sys.exit(proc.returncode)


def git_head(repo: Path) -> str:
    try:
        return subprocess.run(
            ["git", "rev-parse", "HEAD"], cwd=repo, capture_output=True, text=True
        ).stdout.strip()
    except Exception:
        return ""


def load_knowledge(out_dir: Path):
    raw = json.loads((out_dir / "graph.json").read_text(encoding="utf-8"))
    nodes = [dict(n) for n in raw.get("nodes", [])]
    links = [dict(l) for l in raw.get("links", raw.get("edges", []))]
    return raw, nodes, links


def build_adj(nodes: list[dict], links: list[dict]) -> dict[str, set[str]]:
    adj: dict[str, set[str]] = {n["id"]: set() for n in nodes}
    for l in links:
        a, b = l.get("source"), l.get("target")
        if a in adj and b in adj:
            adj[a].add(b)
            adj[b].add(a)
    return adj


def slice_ids(nodes: list[dict], adj: dict[str, set[str]],
              files: list[str], allowlist: tuple[str, ...]) -> set[str]:
    file_by_id = {n["id"]: n for n in nodes}
    focal = {n["id"] for n in nodes if _norm(n.get("source_file", "") or "") in files}
    selected = set(focal)
    for fid in focal:
        for nb in adj.get(fid, ()):
            nf = _norm(file_by_id[nb].get("source_file", "") or "")
            if any(nf.startswith(p) for p in allowlist):
                selected.add(nb)
    if len(selected) > MAX_NODES:
        selected = set(focal)
        for fid in focal:
            for nb in adj.get(fid, ()):
                nf = _norm(file_by_id[nb].get("source_file", "") or "")
                if nf.startswith("backend/app/") or nf.startswith("backend/alembic/"):
                    selected.add(nb)
    if len(selected) > MAX_NODES + 500:
        selected = set(focal)
        for fid in focal:
            for nb in adj.get(fid, ()):
                nf = _norm(file_by_id[nb].get("source_file", "") or "")
                if nf.startswith("backend/app/"):
                    selected.add(nb)
    return selected


def emit_html(py: str, out_dir: Path, out_path: Path, selected_ids: set[str] | None) -> tuple[int, int]:
    """Render an interactive HTML via Graphify's own to_html (custom output path)."""
    ids_json = json.dumps(sorted(selected_ids)) if selected_ids is not None else "None"
    script = f"""
import json, sys
from pathlib import Path
from networkx.readwrite import json_graph as _jg
from graphify.export import to_html as _to_html

out_dir = Path({str(out_dir)!r})
out = Path({str(out_path)!r})
raw = json.loads((out_dir / "graph.json").read_text(encoding="utf-8"))
ids = {ids_json}
if ids is not None:
    keep = set(ids)
    raw["nodes"] = [n for n in raw["nodes"] if n["id"] in keep]
    raw["links"] = [e for e in raw.get("links", raw.get("edges", []))
                    if e.get("source") in keep and e.get("target") in keep]
    raw["directed"] = False
G = _jg.node_link_graph(raw, edges="links")
communities = {{}}
for nid, data in G.nodes(data=True):
    cid = data.get("community")
    if cid is None:
        continue
    try:
        cid = int(cid)
    except (TypeError, ValueError):
        continue
    communities.setdefault(cid, []).append(str(nid))
labels = {{}}
lbl = out_dir / ".graphify_labels.json"
if lbl.exists():
    labels = {{int(k): v for k, v in json.loads(lbl.read_text(encoding="utf-8")).items()}}
labels = {{cid: name for cid, name in labels.items() if cid in communities}}
ok = _to_html(G, communities, str(out), community_labels=labels or None, node_limit=6000)
print(f"NODES={{G.number_of_nodes()}} EDGES={{G.number_of_edges()}}")
if not ok:
    print("to_html returned False", file=sys.stderr)
    sys.exit(2)
"""
    import tempfile
    fd, tmp = tempfile.mkstemp(suffix=".py", prefix="graphify_gen_")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            fh.write(script)
        proc = subprocess.run([py, tmp], capture_output=True, text=True)
    finally:
        try:
            os.unlink(tmp)
        except OSError:
            pass
    if proc.returncode != 0:
        print(proc.stdout, file=sys.stderr)
        print(proc.stderr, file=sys.stderr)
        print(f"error: to_html failed for {out_path}", file=sys.stderr)
        sys.exit(proc.returncode)
    for line in (proc.stdout or "").splitlines():
        if line.startswith("NODES="):
            match = re.match(r"NODES=(\d+)\s+EDGES=(\d+)", line)
            if match:
                return int(match.group(1)), int(match.group(2))
    return -1, -1


def main() -> None:
    ap = argparse.ArgumentParser(description="Regenerate the RezorPay Graphify layer")
    ap.add_argument("--repo", default=None, help="repository root (default: two levels above this script)")
    ap.add_argument("--force-extract", action="store_true", help="re-extract code even if the graph looks current")
    ap.add_argument("--dry-run", action="store_true", help="print sizes only, write nothing")
    args = ap.parse_args()

    repo = Path(args.repo).resolve() if args.repo else Path(__file__).resolve().parents[2]
    out_dir = repo / OUT_NAME
    sub_dir = out_dir / SUBSYSTEM_DIR

    if args.dry_run:
        try:
            _, nodes, links = load_knowledge(out_dir)
        except FileNotFoundError:
            print(f"error: {out_dir / 'graph.json'} not found", file=sys.stderr)
            sys.exit(1)
        adj = build_adj(nodes, links)
        print(f"graph: {len(nodes)} nodes / {len(links)} edges")
        for name, (title, files) in SUBSYSTEMS.items():
            sel = slice_ids(nodes, adj, files, NEIGHBOR_ALLOWLIST)
            file_by_id = {n["id"]: n for n in nodes}
            focal = {n["id"] for n in nodes if _norm(n.get("source_file", "") or "") in files}
            if not focal:
                print(f"  {name}: no focal nodes - SKIP")
                continue
            e = sum(1 for l in links if l.get("source") in sel and l.get("target") in sel)
            print(f"  {name}: focal={len(focal)} total={len(sel)} edges={e}")
        return

    graphify = find_graphify()
    if isinstance(graphify, list):
        graphify_cli: list[str] = graphify
        py = graphify_cli[0]
    else:
        graphify_cli = [graphify]
        python = shutil.which("python") or sys.executable
        py = (graphify[:-len("graphify.exe")] + "python.exe"
              if graphify.endswith("graphify.exe") else python)

    head = git_head(repo)
    graph_json = out_dir / "graph.json"
    run_extract = args.force_extract
    if graph_json.exists():
        try:
            built = json.loads(graph_json.read_text(encoding="utf-8")).get("built_at_commit")
        except Exception:
            built = None
        if built == head:
            print(f"[graphify] graph.json up to date at {head}")
        else:
            run_extract = True
            print(f"[graphify] graph is stale (built {built} != HEAD {head})")
    else:
        run_extract = True

    if run_extract:
        run_cli(graphify_cli, "update", str(repo))
    else:
        print("[graphify] skipping extract (graph already at HEAD)")

    # STEP 3: high-level overview with deterministic hub labels (never --no-label).
    run_cli(graphify_cli, "cluster-only", str(repo))

    # STEP 4: hierarchy.
    run_cli(graphify_cli, "tree", "--graph", str(graph_json),
            "--output", str(out_dir / "GRAPH_TREE.html"))

    # STEP 5: call flow.
    run_cli(graphify_cli, "export", "callflow-html", str(repo),
            "--output", str(out_dir / "rezorpay_pro-callflow.html"))

    # STEPS 6-7: subsystem graphs + STEP 8: full detail (custom output paths).
    _, nodes, links = load_knowledge(out_dir)
    adj = build_adj(nodes, links)
    sub_dir.mkdir(parents=True, exist_ok=True)
    results: list[tuple[str, int, int]] = []

    for name, (title, files) in SUBSYSTEMS.items():
        sel = slice_ids(nodes, adj, files, NEIGHBOR_ALLOWLIST)
        if not sel:
            print(f"[graphify] subgraph '{name}': no focal nodes - SKIPPED")
            continue
        out = sub_dir / f"{name}.html"
        n, e = emit_html(py, out_dir, out, sel)
        results.append((f"subgraphs/{name}.html", n, e))

    full_out = out_dir / "full-detail.html"
    n, e = emit_html(py, out_dir, full_out, None)
    results.append(("full-detail.html", n, e))

    print("\n=== Graphify regeneration complete ===")
    print(f"repo:  {repo}")
    print(f"graph: {len(nodes)} nodes / {len(links)} edges")
    for name, n, e in results:
        print(f"  {name}: {n} nodes / {e} edges")
    print(f"output: {out_dir}")


if __name__ == "__main__":
    main()