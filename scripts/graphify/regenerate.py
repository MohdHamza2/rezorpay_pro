#!/usr/bin/env python3
"""
Graphify regeneration helper for the RezorPay repo.

Builds the layered Graphify documentation system in graphify-out/:

  graph.html                  high-level aggregated community overview
                              (deterministic hub labels; no LLM required)
  GRAPH_TREE.html             project/file hierarchy (D3 collapsible tree)
  rezorpay_pro-callflow.html  architecture / call-flow sections (Mermaid)
  full-detail.html            the complete detailed graph
  subgraphs/<name>.html       focused subsystem graphs
  GRAPH_REPORT.md             Graphify's own text report
  graph.json                  canonical machine-readable graph

Every artifact is generated by Graphify itself (CLI subprocess for
tree/callflow/labels, `graphify.export.to_html` for graphs that need a custom
output path). No application code is touched.

Usage:
  python scripts/graphify/regenerate.py [--repo PATH] [--force-extract]
                                        [--dry-run]

  --force-extract  re-extract code (graphify update) even if the graph appears
                   current (built_at_commit == HEAD). Default is to re-cluster
                   the existing graph when it is already up to date.
  --dry-run        print the subsystem/node sizes that would be generated
                   without writing any files.

Graphify must be installed. It is resolved, in order, from:
  1. $GRAPHIFY_VENV        (directory containing Scripts/graphify.exe on
                            Windows or bin/graphify on POSIX)
  2. `graphify` on PATH
"""

